//Default options (not modifiable)
string kDefOptGeomLUnits            = "mm";    // default geometry length units (not modifiable)
string kDefOptGeomDUnits            = "g_cm3"; // default geometry density units (not modifiable)
std::map<int,string> kDefFluxHistos = { { 12, "NuE" },
                                        { 14, "NuMu" },
                                        { 16, "NuTau" },
                                        { -12, "AntiNuE" },
                                        { -14, "AntiNuMu" },
                                        { -16, "AntiNuTau" }
                                      };
double kDefOptStartPosLng           = -5.5; // neutrino longitudinal (z) start position (in m?) for histogram fluxes
double kDefOptTransRad              = 1.00;   // radius of neutrino start plane (in m?) for histogram fluxes
string kDefFluxTree                 = "flux";  // name of gSimpleNtpFlux flux tree
string kDefMetaTree                 = "meta";  // name of gSimpleNtpFlux meta tree

//Default options (override them using the command line arguments):
int           kDefOptNevents   = 0;          // n-events to generate
double        kDefOptFluxNorm     = 150.0;   // std LHC flux norm (inverse fb) for histograms
NtpMCFormat_t kDefOptNtpFormat = kNFGHEP;    // ntuple format
Long_t        kDefOptRunNu     = 0;          // default run number
string        kDefOptEvFilePrefix = "gntp";  // Output file name prefix


//User-specified options:
Long_t          gOptRunNu;                     // run number
int             gOptNevents;                   // n-events to generate
double          gOptLuminosity;                // integrated luminosity to generate (fb^-1)
long int        gOptNeutrinosToThrow;          // integrated neutrino flux when luminosity normalized
double          gOptFluxNorm;                  // normalization of flux histograms (fb^-1)
bool            gOptUsingRootGeom = false;     // using root geom or target mix?
string          gOptFluxFile;                  // ROOT file with flux histograms
map<int,double> gOptTgtMix;                    // target mix  (tgt pdg -> wght frac) / if not using detailed root geom
map<int,TH1D*>  gOptFluxHst;                   // flux histos (nu pdg  -> spectrum) 
vector<string>  gOptFluxTree;                  // GSimpleNtpFlux files
bool            gOptUsingFluxHst = false;
bool            gOptUsingFluxTree = false;
string          gOptFluxDriver = "";           // Flux driver name
string          gOptRootGeom;                  // input ROOT file with realistic detector geometry
string          gOptRootGeomTopVol = "";       // input geometry top event generation volume
double          gOptGeomLUnits = 0;            // input geometry length units
double          gOptGeomDUnits = 0;            // input geometry density units
string          gOptExtMaxPlXml;               // max path lengths XML file for input geometry
string          gOptEvFilePrefix;              // event file prefix (incl. output directory)
string          gOptOutputDir;                 // output directory ("" = current directory)
long int        gOptRanSeed;                   // random number seed
string          gOptInpXSecFile;               // cross-section splines
bool            gOptWriteGFaser = false;       // also write the flat gFaser ntuple
bool            gOptGFaserCCOnly = false;      // ... with CC events only

//____________________________________________________________________________
int main(int argc, char ** argv)
{
  GetCommandLineArgs(argc,argv);
  Initialize();

  // throw on NaNs and Infs...
#if defined(HAVE_FENV_H) && defined(HAVE_FEENABLEEXCEPT)
  feenableexcept(FE_DIVBYZERO | FE_INVALID | FE_OVERFLOW);
#endif

  GeomAnalyzerI * geom_driver = 0;
  double zmin=0, zmax=0;

  if(gOptUsingRootGeom) 
  {
    //
    // *** Using a realistic root-based detector geometry description
    //
    geometry::FaserROOTGeomAnalyzer * rgeom =
            new geometry::FaserROOTGeomAnalyzer(gOptRootGeom);
    rgeom -> SetLengthUnits  (gOptGeomLUnits);
    rgeom -> SetDensityUnits (gOptGeomDUnits);
    // getting the bounding box dimensions, before setting topvolume,
    // along z so as to set the appropriate upstream generation surface
    // for the JPARC flux driver
    TGeoVolume * topvol = rgeom->GetGeometry()->GetTopVolume();
    TGeoShape * bounding_box = topvol->GetShape();
    bounding_box->GetAxisRange(3, zmin, zmax);
    zmin *= rgeom->LengthUnits();
    zmax *= rgeom->LengthUnits();
    // now update to the requested topvolume for use in recursive exhaust method
    rgeom -> SetTopVolName   (gOptRootGeomTopVol);
    topvol = rgeom->GetGeometry()->GetTopVolume();
    if(!topvol) {
      LOG("gevgen_faser", pFATAL) << "Null top ROOT geometry volume!";
      exit(1);
    }
    // switch on/off volumes as requested
    if ( (gOptRootGeomTopVol[0] == '+') || (gOptRootGeomTopVol[0] == '-') ) {
      bool exhaust = (*gOptRootGeomTopVol.c_str() == '+');
      utils::geometry::RecursiveExhaust(topvol, gOptRootGeomTopVol, exhaust);
    }
    geom_driver = dynamic_cast<GeomAnalyzerI *> (rgeom);
  }
  else 
  {
    //
    // *** Using a 'point' geometry with the specified target mix
    // *** ( = a list of targets with their corresponding weight fraction)
    //
    geometry::PointGeomAnalyzer * pgeom =
              new geometry::PointGeomAnalyzer(gOptTgtMix);
    geom_driver = dynamic_cast<GeomAnalyzerI *> (pgeom);
  }

  // *************************************************************************
  // * Create / configure the flux driver
  // *************************************************************************
  GFluxI * flux_driver = 0;
  flux::GCylindTH1Flux * hst_flux_driver   = 0;
  flux::GSimpleNtpFlux* ntp_flux_driver = 0;
  double integratedFlux = 0.0;
  if (gOptFluxHst.size() > 0)
  {
    TVector3 bdir (0,0,1); // dir along +z
    TVector3 bspot(0,0,kDefOptStartPosLng);
    hst_flux_driver = new flux::GCylindTH1Flux;
    hst_flux_driver->SetNuDirection      (bdir);
    hst_flux_driver->SetBeamSpot         (bspot);
    hst_flux_driver->SetTransverseRadius (kDefOptTransRad);
    map<int,TH1D*>::iterator it = gOptFluxHst.begin();
    for( ; it != gOptFluxHst.end(); ++it) {
        int    pdg_code = it->first;
        if (gOptLuminosity > 0)
          integratedFlux += it->second->Integral("width");
        TH1D * spectrum = new TH1D(*(it->second));
        hst_flux_driver->AddEnergySpectrum(pdg_code, spectrum);
    }
    flux_driver = dynamic_cast<GFluxI *> (hst_flux_driver);
    gOptUsingFluxHst = true;
  }
  else if (gOptFluxTree.size() > 0)
  {
    ntp_flux_driver = new flux::GSimpleNtpFlux;
    ntp_flux_driver->LoadBeamSimData(gOptFluxTree, "");
    flux_driver = dynamic_cast<GFluxI*> (ntp_flux_driver);
    gOptUsingFluxTree = true;
  }
  // these might come in handy ... avoid repeated dynamic_cast<> calls
  genie::flux::GFluxExposureI* fluxExposureI =
    dynamic_cast<genie::flux::GFluxExposureI*>(flux_driver);
  genie::flux::GFluxFileConfigI* fluxFileConfigI =
    dynamic_cast<genie::flux::GFluxFileConfigI*>(flux_driver);


  // *************************************************************************
  // * Create/configure the event generation driver
  // *************************************************************************
  FaserGMCJDriver * mcj_driver = new FaserGMCJDriver;
  mcj_driver->SetEventGeneratorList(RunOpt::Instance()->EventGeneratorList());
  mcj_driver->UseFluxDriver(flux_driver);
  mcj_driver->UseGeomAnalyzer(geom_driver);
  mcj_driver->UseMaxPathLengths(gOptExtMaxPlXml);
  mcj_driver->Configure();
  mcj_driver->UseSplines();
  mcj_driver->ForceSingleProbScale();

  // *************************************************************************
  // * Work out number of neutrinos for current exposure settings
  // *************************************************************************
  if (gOptLuminosity > 0)
  {
    LOG("gevgen_faser", pINFO) << "Luminosity normalization requested was "
      << gOptLuminosity << " inverse femtobarns";
    if (gOptFluxHst.size() != 0)
    {
      // Flux histograms are per cm^2
      integratedFlux *= constants::kPi * pow( 100.0 * kDefOptTransRad, 2);
      integratedFlux *= gOptLuminosity/gOptFluxNorm;
      gOptNeutrinosToThrow = lround(integratedFlux * mcj_driver->GlobProbScale());
      LOG("gevgen_faser", pINFO) << "Throwing " 
        << gOptNeutrinosToThrow << " neutrinos in luminosity-normalized histogram flux mode";
    }
  }

  // *************************************************************************
  // * Prepare for writing the output event tree & status file
  // *************************************************************************

  // Initialize an Ntuple Writer to save GHEP records into a TTree
  NtpWriter ntpw(kDefOptNtpFormat, gOptRunNu);
  ntpw.CustomizeFilenamePrefix(gOptEvFilePrefix);
  ntpw.Initialize();

  // Optionally, the flat gFaser ntuple ([prefix].[run].gfaser.root)
  GFaserNtpWriter gfaserw;
  string gfaser_filename;
  if (gOptWriteGFaser) {
    ostringstream fn;
    fn << gOptEvFilePrefix << "." << gOptRunNu << ".gfaser.root";
    gfaser_filename = fn.str();
    if (!gfaserw.Open(gfaser_filename, gOptGFaserCCOnly)) {
      LOG("gevgen_faser", pFATAL) << "Cannot open " << gfaser_filename;
      exit(1);
    }
    LOG("gevgen_faser", pNOTICE) << "Also writing the gFaser ntuple to " << gfaser_filename
                                 << (gOptGFaserCCOnly ? " (CC events only)" : "");
  }

  // Create a MC job monitor for a periodically updated status file
  GMCJMonitor mcjmonitor(gOptRunNu);
  {
    // status file next to the event files
    string dir = gOptEvFilePrefix.substr(0, gOptEvFilePrefix.find_last_of('/') + 1);
    ostringstream sf; sf << dir << "genie-mcjob-" << gOptRunNu << ".status";
    mcjmonitor.CustomizeFilename(sf.str());
  }
  mcjmonitor.SetRefreshRate(RunOpt::Instance()->MCJobStatusRefreshRate());

  // *************************************************************************
  // * Event generation loop
  // *************************************************************************

  int ievent = 0;
  bool moreNeutrinos = true;
  while (moreNeutrinos)
  {
     LOG("gevgen_faser", pNOTICE)
          << " *** Generating event............ " << ievent;

     // In case the required statistics was expressed as 'number of events'
     // then quit if that number has been generated
     if(ievent == gOptNevents) break;

     // Generate a single event using neutrinos coming from the specified flux
     // and hitting the specified geometry or target mix
     EventRecord * event = mcj_driver->GenerateEvent();

     // If we needed more neutrinos than the requested luminosity, reject the event
     moreNeutrinos = (gOptLuminosity <= 0 || 
      (gOptUsingFluxHst && (mcj_driver->NFluxNeutrinos() <= gOptNeutrinosToThrow)) ||
      (gOptUsingFluxTree && (ntp_flux_driver->GetTotalExposure()/mcj_driver->GlobProbScale() <= gOptLuminosity)));
     if (moreNeutrinos)
     {
      LOG("gevgen_faser", pINFO)
         << "Generated event: " << *event;

      // Add event at the output ntuple, refresh the mc job monitor & clean-up
      ntpw.AddEventRecord(ievent, event);
      if (gOptWriteGFaser) gfaserw.Add(*event);
      mcjmonitor.Update(ievent,event);
      ievent++;
     }
     delete event;
  } //1

  LOG("gevgen_faser", pNOTICE)
    << "The GENIE MC job is done generaing events - Cleaning up & exiting...";

  // *************************************************************************
  // * Print job statistics &
  // * calculate normalization factor for the generated sample
  // *************************************************************************
  double gfaser_pot = 0;
  if ( !gOptUsingFluxHst && gOptUsingRootGeom ) {
    // POT normalization will only be calculated if event generation was based
    // on beam simulation ntuples (not just histograms) & a detailed detector
    // geometry description.
    // Get nunber of flux neutrinos read-in by flux driver, number of flux
    // neutrinos actually thrown to the event generation driver and number
    // of neutrino interactions actually generated
    long int nflx     = 0;
    long int nflx_evg = mcj_driver-> NFluxNeutrinos();
    double   fpot     = 0;
    const char* exposureUnits = "(unknown units)";
    if ( fluxExposureI ) {
      fpot = fluxExposureI->GetTotalExposure(); // POTs used so far
      nflx = fluxExposureI->NFluxNeutrinos();
      //genie::flux::Exposure_t etype = fluxExposureI->GetExposureType();
      //exposureUnits = genie::flux::GFluxExposureI::AsString(etype);
      exposureUnits = fluxExposureI->GetExposureUnits();
    }
    if ( fluxFileConfigI ) {
      fluxFileConfigI->PrintConfig();
    }
    double psc   = mcj_driver->GlobProbScale();      // interaction prob. scale
    if ( psc <= 0.0 ) {
       LOG("gevgen_faser", pFATAL) << "MCJobDriver GlobalProbScale was " << psc;
    }
    double pot   = fpot / psc;                       // POT for generated sample
    long int nev = ievent;

    LOG("gevgen_faser", pNOTICE)
        << "\n >> Interaction probability scaling factor:  " << psc
        << "\n >> using: " << gOptFluxDriver << " driver"
        << "\n >> N of flux v read-in by flux driver:      " << nflx
        << "\n >> N of flux v thrown to event gen driver:  " << nflx_evg
        << "\n >> N of generated v interactions:           " << nev
        << "\n ** Normalization for generated sample:      " << pot
        << " " << exposureUnits << " * detector";

    ntpw.EventTree()->SetWeight(pot); // store POT
    gfaser_pot = pot;
  }

  // *************************************************************************
  // * Save & clean-up
  // *************************************************************************

  // Save the generated event tree & close the output file
  if (gOptWriteGFaser) {
    LOG("gevgen_faser", pNOTICE) << "Saving " << gfaserw.Entries()
                                 << " events in " << gfaser_filename;
    gfaserw.Save(gfaser_pot);
  }
  ntpw.Save();

  // Clean-up
  delete geom_driver;
  delete flux_driver;
  delete mcj_driver;
  map<int,TH1D*>::iterator it = gOptFluxHst.begin();
  for( ; it != gOptFluxHst.end(); ++it) {
    TH1D * spectrum = it->second;
    if(spectrum) delete spectrum;
  }
  gOptFluxHst.clear();
  gOptFluxTree.clear();

  LOG("gevgen_faser", pNOTICE) << "Done!";

  return 0;
}
