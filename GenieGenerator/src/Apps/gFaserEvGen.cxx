void GetCommandLineArgs(int argc, char ** argv)
{
  LOG("gevgen_faser", pINFO) << "Parsing command line arguments";

  // Common run options. Set defaults and read.
  RunOpt::Instance()->EnableBareXSecPreCalc(true);
  RunOpt::Instance()->ReadFromCommandLine(argc,argv);

  // Parse run options for this app

  CmdLnArgParser parser(argc,argv);

  // help?
  bool help = parser.OptionExists('h');
  if(help) {
      PrintSyntax();
      exit(0);
  }

  // flux file luminosity normalization
  // only relevant when using the JNUBEAM flux ntuples
  if( parser.OptionExists('L') ) {
    LOG("gevgen_faser", pDEBUG)  << "Reading flux file normalization";
    gOptFluxNorm = parser.ArgAsDouble('L');
  } else {
    LOG("gevgen_faser", pDEBUG)
        << "Setting standard normalization for flux histograms (if any)";
    gOptFluxNorm = kDefOptFluxNorm;
  } //-p

  // limit on max number of events that can be generated
  if( parser.OptionExists('n') ) {
    LOG("gevgen_faser", pDEBUG)
        << "Reading limit on number of events to generate";
    gOptNevents = parser.ArgAsInt('n');
  } else {
    LOG("gevgen_faser", pDEBUG)
      << "Will generate events until specified luminosity is reached";
    gOptNevents = -1;
  } //-n

  // exposure (in inverse fb)
  if( parser.OptionExists('l') ) {
    LOG("gevgen_faser", pDEBUG)  << "Generating requested exposure in inverse fb";
    gOptLuminosity = parser.ArgAsDouble('l');
  } else {
    LOG("gevgen_faser", pDEBUG) << "No POT exposure was requested";
    gOptLuminosity = -1;
  } //-l

  // event file prefix
  if( parser.OptionExists('o') ) {
    LOG("gevgen_faser", pDEBUG) << "Reading the event filename prefix";
    gOptEvFilePrefix = parser.ArgAsString('o');
  } else {
    LOG("gevgen_faser", pDEBUG)
      << "Will set the default event filename prefix";
    gOptEvFilePrefix = kDefOptEvFilePrefix;
  } //-o

  // output directory: --output-dir, else $GENIE_OUTPUT, else the current directory;
  // a prefix that already contains a directory is used as given
  if( parser.OptionExists("output-dir") ) {
    gOptOutputDir = parser.ArgAsString("output-dir");
  } else if ( std::getenv("GENIE_OUTPUT") ) {
    gOptOutputDir = std::getenv("GENIE_OUTPUT");
  }
  if ( gOptEvFilePrefix.find('/') != string::npos ) gOptOutputDir = "";
  if ( !gOptOutputDir.empty() ) {
    gSystem->mkdir(gOptOutputDir.c_str(), kTRUE);
    if ( gOptOutputDir.back() != '/' ) gOptOutputDir += "/";
    gOptEvFilePrefix = gOptOutputDir + gOptEvFilePrefix;
    LOG("gevgen_faser", pNOTICE) << "Output files go to " << gOptOutputDir;
  }

  // run number
  if( parser.OptionExists('r') ) {
    LOG("gevgen_faser", pINFO) << "Reading MC run number";
    gOptRunNu = parser.ArgAsLong('r');
  } else {
    LOG("gevgen_faser", pINFO) << "Unspecified run number - Using default";
    gOptRunNu = kDefOptRunNu;
  }

  // geometry
  ParseGeometryOption(parser);

  // flux
  ParseFluxOption(parser);

  // random number seed
  gOptGFaserCCOnly = parser.OptionExists("gfaser-cc-only");
  gOptWriteGFaser  = parser.OptionExists("gfaser") || gOptGFaserCCOnly;

  if( parser.OptionExists("seed") ) {
    LOG("gevgen_faser", pINFO) << "Reading random number seed";
    gOptRanSeed = parser.ArgAsLong("seed");
  } else {
    LOG("gevgen_faser", pINFO) << "Unspecified random number seed - Using default";
    gOptRanSeed = controls::kDefaultRandSeed;
  }

  // input cross-section file
  if( parser.OptionExists("cross-sections") ) {
    LOG("gevgen_faser", pINFO) << "Reading cross-section file";
    gOptInpXSecFile = parser.ArgAsString("cross-sections");
  } else {
    LOG("gevgen_faser", pINFO) << "Unspecified cross-section file";
    gOptInpXSecFile = "";
  }
  //
  //  "Sanity" check(s)
  //
  // If we don't use a detailed ROOT detector geometry (but just a target mix) then
  // don't accept luminosity as a way to control job statistics (not enough info is passed
  // in the target mix to compute luminosity & the calculation can be easily done offline)
  if(!gOptUsingRootGeom) {
    if(gOptLuminosity > 0) {
       LOG("gevgen_faser", pFATAL)
         << "You may not use the -l option "
         << "without a detailed detector geometry description input";
       exit(1);
    }
  }
  //
  // print-out the command line options
  //
  PDGLibrary * pdglib = PDGLibrary::Instance();

  ostringstream gminfo;
  if (gOptUsingRootGeom) {
    gminfo << "Using ROOT geometry - file: " << gOptRootGeom
           << ", top volume: "
           << ((gOptRootGeomTopVol.size()==0) ? "<master volume>" : gOptRootGeomTopVol)
           << ", max{PL} file: "
           << ((gOptExtMaxPlXml.size()==0) ? "<none>" : gOptExtMaxPlXml)
           << ", length  units: " << kDefOptGeomLUnits
           << ", density units: " << kDefOptGeomDUnits;
  } else {
    gminfo << "Using target mix - ";
    map<int,double>::const_iterator iter;
    for(iter = gOptTgtMix.begin(); iter != gOptTgtMix.end(); ++iter) {
          int    pdg_code = iter->first;
          double wgt      = iter->second;
          TParticlePDG * p = pdglib->Find(pdg_code);
          if(p) {
            string name = p->GetName();
            gminfo << "(" << name << ") -> " << 100*wgt << "% / ";
          }//p?
    }
  }

  ostringstream fluxinfo;
  fluxinfo << "Using flux histograms - ";
  map<int,TH1D*>::const_iterator iter;
  for(iter = gOptFluxHst.begin(); iter != gOptFluxHst.end(); ++iter) {
      int    pdg_code = iter->first;
      TH1D * spectrum = iter->second;
      TParticlePDG * p = pdglib->Find(pdg_code);
      if(p) {
        string name = p->GetName();
        fluxinfo << "(" << name << ") -> " << spectrum->GetName() << " / ";
      }//p?
    }

  ostringstream exposure;
  if(gOptLuminosity > 0)
      exposure << "Number of inverse fb = " << gOptLuminosity;
  if(gOptNevents > 0)
      exposure << "Number of events = " << gOptNevents;

  LOG("gevgen_faser", pNOTICE)
     << "\n\n"
     << utils::print::PrintFramedMesg("Faser event generation job configuration");

  LOG("gevgen_faser", pNOTICE)
     << "\n -  Run number: " << gOptRunNu
     << "\n -  Random number seed: " << gOptRanSeed
     << "\n - Using cross-section file: " << gOptInpXSecFile
     << "\n - Flux     @ " << fluxinfo.str()
     << "\n - Geometry @ " << gminfo.str()
     << "\n - Exposure @ " << exposure.str();

  LOG("gevgen_faser", pNOTICE) << *RunOpt::Instance();

}
//
void ParseGeometryOption(CmdLnArgParser& parser)
{
  string geom = "";
  string lunits, dunits;
  if( parser.OptionExists('g') ) {
    LOG("gevgen_faser", pDEBUG) << "Getting input geometry";
    geom = parser.ArgAsString('g');

    // is it a ROOT file that contains a ROOT geometry?
    bool accessible_geom_file =
            ! (gSystem->AccessPathName(geom.c_str()));
    if (accessible_geom_file) {
      gOptRootGeom      = geom;
      gOptUsingRootGeom = true;
    }
  } else {
      LOG("gevgen_faser", pFATAL)
        << "No geometry option specified - Exiting";
      PrintSyntax();
      exit(1);
  } //-g

  if(gOptUsingRootGeom) {
     // using a ROOT geometry - get requested geometry units

     // legth units:
    //  if( parser.OptionExists('L') ) {
    //     LOG("gevgen_faser", pDEBUG)
    //        << "Checking for input geometry length units";
    //     lunits = parser.ArgAsString('L');
    //  } else {
    //     LOG("gevgen_faser", pDEBUG) << "Using default geometry length units";
    //     lunits = kDefOptGeomLUnits;
    //  } // -L
    //  // density units:
    //  if( parser.OptionExists('D') ) {
    //     LOG("gevgen_faser", pDEBUG)
    //        << "Checking for input geometry density units";
    //     dunits = parser.ArgAsString('D');
    //  } else {
    //     LOG("gevgen_faser", pDEBUG) << "Using default geometry density units";
    //     dunits = kDefOptGeomDUnits;
    //  } // -D
     gOptGeomLUnits = genie::utils::units::UnitFromString(kDefOptGeomLUnits);
     gOptGeomDUnits = genie::utils::units::UnitFromString(kDefOptGeomDUnits);

     // check whether an event generation volume name has been
     // specified -- default is the 'top volume'
     if( parser.OptionExists('t') ) {
        LOG("gevgen_faser", pDEBUG) << "Checking for input volume name";
        gOptRootGeomTopVol = parser.ArgAsString('t');
     } else {
        LOG("gevgen_faser", pDEBUG) << "Using the <master volume>";
     } // -t

     // check whether an XML file with the maximum (density weighted)
     // path lengths for each detector material is specified -
     // otherwise will compute the max path lengths at job init
     if( parser.OptionExists('m') ) {
        LOG("gevgen_faser", pDEBUG)
              << "Checking for maximum path lengths XML file";
        gOptExtMaxPlXml = parser.ArgAsString('m');
     } else {
        LOG("gevgen_faser", pDEBUG)
           << "Will compute the maximum path lengths at job init";
        gOptExtMaxPlXml = "";
     } // -m
  } // using root geom?

  else {
    // User has specified a target mix.
    // Decode the list of target pdf codes & their corresponding weight fraction
    // (specified as 'pdg_code_1[fraction_1],pdg_code_2[fraction_2],...')
    // See documentation on top section of this file.
    //
    gOptTgtMix.clear();
    vector<string> tgtmix = utils::str::Split(geom,",");
    if(tgtmix.size()==1) {
         int    pdg = atoi(tgtmix[0].c_str());
         double wgt = 1.0;
         gOptTgtMix.insert(map<int, double>::value_type(pdg, wgt));
    } else {
      vector<string>::const_iterator tgtmix_iter = tgtmix.begin();
      for( ; tgtmix_iter != tgtmix.end(); ++tgtmix_iter) {
         string tgt_with_wgt = *tgtmix_iter;
         string::size_type open_bracket  = tgt_with_wgt.find("[");
         string::size_type close_bracket = tgt_with_wgt.find("]");
         if (open_bracket ==string::npos ||
             close_bracket==string::npos)
         {
             LOG("gevgen_faser", pFATAL)
                << "You made an error in specifying the target mix";
             PrintSyntax();
             exit(1);
         }
         string::size_type ibeg = 0;
         string::size_type iend = open_bracket;
         string::size_type jbeg = open_bracket+1;
         string::size_type jend = close_bracket;
         int    pdg = atoi(tgt_with_wgt.substr(ibeg,iend-ibeg).c_str());
         double wgt = atof(tgt_with_wgt.substr(jbeg,jend-jbeg).c_str());
         LOG("gevgen_faser", pDEBUG)
            << "Adding to target mix: pdg = " << pdg << ", wgt = " << wgt;
         gOptTgtMix.insert(map<int, double>::value_type(pdg, wgt));

      }// tgtmix_iter
    } // >1 materials in mix
  } // using tgt mix?
}

void ParseFluxOption(CmdLnArgParser& parser)
{
  //
  // *** flux
  //

  if( parser.OptionExists('f') ) {
    LOG("gevgen_faser", pDEBUG) << "Getting input flux";
    gOptFluxHst.clear();  // make sure list of histograms starts empty
    string flux = parser.ArgAsString('f');
    vector<string> fluxv = utils::str::Split(flux,",");

    // See if we have a comma-separated list of GSimpleNtpFlux files
    for (size_t iFile = 0; iFile < fluxv.size(); iFile++)
    {
      gOptFluxFile = fluxv[iFile];
      bool accessible_flux_file =
              !(gSystem->AccessPathName(gOptFluxFile.c_str()));
      if (!accessible_flux_file) {
          LOG("gevgen_faser", pDEBUG)
            << "Can not access flux file: " << gOptFluxFile << ". Looking for flux histograms instead.";
          gOptFluxTree.clear();
          break;
      }
      TFile flux_file(gOptFluxFile.c_str(), "read");
      // Check whether file contains trees expected by GSimpleNtpFlux
      TTree* iFluxTree = dynamic_cast<TTree*>(flux_file.Get(kDefFluxTree.c_str()));
      TTree* iMetaTree = dynamic_cast<TTree*>(flux_file.Get(kDefMetaTree.c_str()));
      flux_file.Close();
      if (iFluxTree != nullptr && iMetaTree != nullptr)
      {
        // Using flux tree(s)
        // Interpret comma-separated list as a list of GSimpleNtpFlux files
        gOptFluxTree.push_back(gOptFluxFile);
      }
      else
      {
        LOG("gevgen_faser", pDEBUG) << gOptFluxFile << " is not a valid GSimpleNtpFlux file. Looking for flux histograms instead.";
        gOptFluxTree.clear();
        break;
      }
    }

    if (!gOptFluxTree.empty()) 
    {
      gOptFluxDriver = "genie::flux::GSimpleNtpFlux";
      return; // Found GSimpleNtpFlux tree(s)
    }

    // Interpret flux option as a histogram file
    gOptFluxDriver = "genie::flux::GCylindTH1Flux";
    gOptFluxFile = fluxv[0];
    bool accessible_flux_file =
          !(gSystem->AccessPathName(gOptFluxFile.c_str()));
    if (!accessible_flux_file) {
        LOG("gevgen_faser", pFATAL)
          << "Can not access flux file: " << gOptFluxFile ;
        PrintSyntax();
        exit(1);
    }
    TFile flux_file(gOptFluxFile.c_str(), "read");
    if (fluxv.size() == 1)
    {
      // User has not specified the names of histograms for each species explicitly
      // Use the defaults
      for (auto entry : kDefFluxHistos)
      {
        int pdg = entry.first;
        string histo = entry.second;
        TH1D* ihst = (TH1D*) flux_file.Get(histo.c_str());
        if(!ihst) continue;
        TString origname = ihst->GetName();
        TString tmpname; tmpname.Form("%s_", origname.Data());
        TH1D * spectrum = new TH1D(
              tmpname.Data(), ihst->GetName(), ihst->GetNbinsX(),
              ihst->GetXaxis()->GetXmin(), ihst->GetXaxis()->GetXmax());
        spectrum->SetDirectory(0);
        for(int ibin = 1; ibin <= ihst->GetNbinsX(); ibin++) {
            spectrum->SetBinContent(ibin, ihst->GetBinContent(ibin));
        }
        // get rid of original
        delete ihst;
        // rename copy
        spectrum->SetName(origname.Data());

        // store flux neutrino code / energy spectrum
        LOG("gevgen_faser", pDEBUG)
          << "Adding energy spectrum for flux neutrino: pdg = " << pdg;
        gOptFluxHst.insert(map<int, TH1D*>::value_type(pdg, spectrum));
      }
      // Make sure we found at least one flux histogram
      if(gOptFluxHst.size()<1) {
        LOG("gevgen_faser", pFATAL)
            << "Your flux file contains no histograms with the expected names!";
        PrintSyntax();
        exit(1);
      }
    }
    else 
    {
      // Extract energy spectra for all specified neutrino species
      for(unsigned int inu=1; inu<fluxv.size(); inu++) {
        string nutype_and_histo = fluxv[inu];
        string::size_type open_bracket  = nutype_and_histo.find("[");
        string::size_type close_bracket = nutype_and_histo.find("]");
        if (open_bracket ==string::npos ||
            close_bracket==string::npos)
        {
            LOG("gevgen_faser", pFATAL)
               << "You made an error in specifying the flux histograms";
            PrintSyntax();
            exit(1);
        }
        string::size_type ibeg = 0;
        string::size_type iend = open_bracket;
        string::size_type jbeg = open_bracket+1;
        string::size_type jend = close_bracket;
        string nutype = nutype_and_histo.substr(jbeg,jend-jbeg);
        string histo  = nutype_and_histo.substr(ibeg,iend-ibeg);
        // access specified histogram from the input root file
        TH1D * ihst = (TH1D*) flux_file.Get(histo.c_str());
        if(!ihst) {
            LOG("gevgen_faser", pFATAL)
              << "Can not find histogram: " << histo
              << " in flux file: " << gOptFluxFile;
            PrintSyntax();
            exit(1);
        }
        // create a local copy of the input histogram
        TString origname = ihst->GetName();
        TString tmpname; tmpname.Form("%s_", origname.Data());
        TH1D * spectrum = new TH1D(
              tmpname.Data(), ihst->GetName(), ihst->GetNbinsX(),
              ihst->GetXaxis()->GetXmin(), ihst->GetXaxis()->GetXmax());
        spectrum->SetDirectory(0);
        for(int ibin = 1; ibin <= ihst->GetNbinsX(); ibin++) {
            spectrum->SetBinContent(ibin, ihst->GetBinContent(ibin));
        }
        // get rid of original
        delete ihst;
        // rename copy
        spectrum->SetName(origname.Data());

        // convert neutrino name -> pdg code
        int pdg = atoi(nutype.c_str());
        if(!pdg::IsNeutrino(pdg) && !pdg::IsAntiNeutrino(pdg)) {
            LOG("gevgen_faser", pFATAL)
                << "Unknown neutrino type: " << nutype;
            PrintSyntax();
            exit(1);
        }
        // store flux neutrino code / energy spectrum
        LOG("gevgen_faser", pDEBUG)
          << "Adding energy spectrum for flux neutrino: pdg = " << pdg;
        gOptFluxHst.insert(map<int, TH1D*>::value_type(pdg, spectrum));
      }//inu
      if(gOptFluxHst.size()<1) {
        LOG("gevgen_faser", pFATAL)
            << "You have not specified any flux histogram!";
        PrintSyntax();
        exit(1);
      }
    } // implicit or explicit histogram association?
    flux_file.Close();

  } else {
      LOG("gevgen_faser", pFATAL) << "No flux info was specified - Exiting";
      PrintSyntax();
      exit(1);
  }
}
