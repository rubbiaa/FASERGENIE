/*!

\program gevgen_faser

\brief  A GENIE v+A event generation driver customized for FASER (gevgen_faser).

        (Based on gevgen and gevgen_t2k)

         This driver can handle the FASER neutrino flux files generated by Felix Kling and the
         realistic detector geometries / target mix of the FASER detector.

         FASER users should note that the generic GENIE event generation driver (gevgen) may
         still be a more appropriate tool to use for the simpler event generation cases
         required for many 4-vector level / systematic studies.
         Please see the GENIE documentation (http://www.genie-mc.org) if in doubt.

         Syntax :
           gevgen_faser [-h]
                        [-r run#]
                         -f flux_file
                         -g geometry
                         --cross-sections xml_file
                        [-n number_of_events_to_generate]
                        [-l luminosity_to_generate]
                        [-L flux_file_lumi_norm]
                        [-o outfile_prefix]
                        [--gfaser] [--gfaser-cc-only]
                        [--output-dir directory]
                        [--seed random_number_seed]
                        [-t top_volume_name_at_geom || -t +Vol1-Vol2...]  
                        [-m max_path_lengths_xml_file]
                        [--tune genie_tune]
                        [--message-thresholds xml_file]
                        [--unphysical-event-mask mask]
                        [--event-record-print-level level]
                        [--mc-job-status-refresh-rate  rate]
                        [--cache-file root_file]
                        [--xml-path config_xml_dir]

         Options :
           [] Denotes an optional argument.
           -h
              Prints-out help on using gevgen and exits.
           -r
              Specifies the MC run number.
           -f
              Specifies a ROOT file with the neutrino flux spectra.
              The contents of the file are inspected to determine whether it contains either:
                A gSimpleNtpFlux tree, or
                Flux histograms.
                  The flux histograms are assumed to be named:
                    NuE
                    NuMu
                    NuTau
                    AntiNuE
                    AntiNuMu
                    AntiNuTau
                  The histogram neutrino directions are parallel to the z-axis.
                  The histogram neutrinos start on a 50 cm radius disk at z = -3000 mm.
           -g
              Input 'geometry'.
              This option can be used to specify any of:
              1 > A gdml or root file containing a ROOT/GEANT geometry description
              2 > A mix of target materials, each with its corresponding weight,
                  typed as a comma-separated list of nuclear PDG codes (in the
                  std PDG2006 convention: 10LZZZAAAI) with the weight fractions
                  in brackets, eg code1[fraction1],code2[fraction2],...
                  If that option is used (no detailed input geometry description)
                  then the interaction vertices are distributed in the detector
                  by the detector MC.
                  [Examples]
                  - To use a target mix of 95% O16 and 5% H type:
                    '-g 1000080160[0.95],1000010010[0.05]'
                  - To use a target which is 100% C12, type:
                    '-g 1000060120'
           --cross-sections
              Name (incl. full path) of an XML file with pre-computed
              cross-section values used for constructing splines.
           -n
              Specifies the number of events to generate.
              Either the number of events or the integrated luminosity to simulate
              must be specifed.
           -l
              Specifies the integrated luminosity (in inverse femtobarns) to simulate.
              Either the number of events or the integrated luminosity to simulate
              must be specifed.
           -L
              Specifies the integrated luminosity normalization (in inverse femtobarns)
              of flux histograms. (Default: 150.0)
              Ignored for flux ntuples.
           -o
              Sets the prefix of the output event file.
              The output filename is built as:
              [prefix].[run_number].[event_tree_format].[file_format]
              The default output filename is:
              gntp.[run_number].ghep.root
              This cmd line arguments lets you override 'gntp'
           --gfaser
              Also write the flat FASER ntuple (tree "gFaser", same branches as
              faser/Ntuple/convertGHEP.C) while generating, to
              [prefix].[run_number].gfaser.root, next to the GHEP file.
           --gfaser-cc-only
              As --gfaser, but keep only charged-current events in the gFaser
              file (the GHEP file still has all events); same selection as
              convertGHEP.C(..., ccOnly=true).
           --output-dir
              Directory for the GHEP file, the gFaser file and the job status file.
              Default: $GENIE_OUTPUT (set by setup.sh to $GENIE_HOME/output), or the
              current directory if GENIE_OUTPUT is not set. Ignored if the -o prefix
              already contains a directory (e.g. -o /scratch/myrun).
           --seed
              Random number seed.
           -t
              Input 'top volume' for event generation -
              can be used to force event generation in given sub-detector.
              [default: the 'master volume' of the input geometry]
              You can also use the -t option to switch generation on/off at
              multiple volumes as, for example, in:
              `-t +Vol1-Vol2+Vol3-Vol4',
              `-t "+Vol1 -Vol2 +Vol3 -Vol4"',
              `-t -Vol2-Vol4+Vol1+Vol3',
              `-t "-Vol2 -Vol4 +Vol1 +Vol3"'m
              where:
              "+Vol1" and "+Vol3" tells GENIE to `switch on'  Vol1 and Vol3, while
              "-Vol2" and "-Vol4" tells GENIE to `switch off' Vol2 and Vol4.
              If the very first character is a '+', GENIE will neglect all volumes
              except the ones explicitly turned on. Vice versa, if the very first
              character is a `-', GENIE will keep all volumes except the ones
              explicitly turned off (feature contributed by J.Holeczek).
           -m
              An XML file (generated by gmxpl) with the max (density weighted)
              path-lengths for each target material in the input ROOT geometry.
              If no file is input, then the geometry will be scanned at MC job
              initialization to determine those max path lengths.
              Supplying this file can speed-up the MC job initialization.
           --event-generator-list
              List of event generators to load in event generation drivers.
              [default: "Default"].
           --tune
              Specifies a GENIE comprehensive neutrino interaction model tune.
              [default: "Default"].
           --message-thresholds
              Allows users to customize the message stream thresholds.
              The thresholds are specified using an XML file.
              See $GENIE/config/Messenger.xml for the XML schema.
           --unphysical-event-mask
              Allows users to specify a 16-bit mask to allow certain types of
              unphysical events to be written in the output file.
              [default: all unphysical events are rejected]
           --event-record-print-level
              Allows users to set the level of information shown when the event
              record is printed in the screen. See GHepRecord::Print().
           --mc-job-status-refresh-rate
              Allows users to customize the refresh rate of the status file.
           --cache-file
              Allows users to specify a cache file so that the cache can be
              re-used in subsequent MC jobs.
           --xml-path
              A directory to load XML files from - overrides $GXMLPATH, and $GENIE/config

        ***  See the User Manual for more details and examples. ***

\author  Costas Andreopoulos <costas.andreopoulos \at stfc.ac.uk>
         University of Liverpool & STFC Rutherford Appleton Lab
\author  Dave Casper <dcasper \at uci.edu>
         Eli Welch <welchem \at uci.edu>
         University of California, Irvine

\created Decemeber 11, 2021

\cpright Copyright (c) 2003-2021, The GENIE Collaboration
         For the full text of the license visit http://copyright.genie-mc.org
         or see $GENIE/LICENSE
*/
